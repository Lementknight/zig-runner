#!/usr/bin/env python3
"""Writes runner/src/unicode_tables.zig: what `\\p{…}` in runner/src/regex.zig reads.

- The general category of every UTF-16 code unit (U+0000 to U+FFFF), from the Unicode Character
  Database's UnicodeData.txt at Unicode 15.0.0, the version .NET 8's char.GetUnicodeCategory
  answers from (U+0CF3, new in 15.0, is a letter there; U+2FFC, new in 15.1, is unassigned).
- .NET's named blocks (`IsBasicLatin`, …, and its `_xml…` classes), as .NET 8 defines them in
  RegexCharClass.s_propTable: its own fixed list, with legacy names and ranges, not Blocks.txt.

Both are downloaded and checked against the SHA-256 below, so the output only changes if this
script does.

    python3 runner/tools/gen_unicode_tables.py > runner/src/unicode_tables.zig
"""
import hashlib
import re
import sys
import urllib.request

UNICODE_DATA = (
    "https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt",
    "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73",
)
REGEX_CHAR_CLASS = (
    "https://raw.githubusercontent.com/dotnet/runtime/v8.0.0/src/libraries/"
    "System.Text.RegularExpressions/src/System/Text/RegularExpressions/RegexCharClass.cs",
    "e37a0e7f9fe15ccca90baf113e1a459f05a8d2acbb0972aecbedaa8b9f02ff89",
)

# .NET's UnicodeCategory, in its order (the enum's values).
CATEGORIES = [
    "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Zs", "Zl", "Zp", "Cc",
    "Cf", "Cs", "Co", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Cn",
]


def fetch(source):
    url, sha256 = source
    with urllib.request.urlopen(url, timeout=60) as r:
        data = r.read()
    got = hashlib.sha256(data).hexdigest()
    if got != sha256:
        sys.exit(f"{url}: SHA-256 {got}, expected {sha256}")
    return data.decode("utf-8")


def categories(text):
    """The category of each code unit 0..0xFFFF; Cn where UnicodeData.txt lists nothing."""
    cat = ["Cn"] * 0x10000
    first = None
    for line in text.splitlines():
        fields = line.split(";")
        cp, name, gc = int(fields[0], 16), fields[1], fields[2]
        if cp > 0xFFFF:
            break
        if name.endswith(", First>"):
            first = cp
            continue
        lo = first if name.endswith(", Last>") else cp
        first = None
        for c in range(lo, cp + 1):
            cat[c] = gc
    return cat


def blocks(source):
    """s_propTable's entries: (name, [(first, last)]), ranges inclusive."""
    body = source[source.index("s_propTable = {"):]
    body = body[: body.index("};")]
    out = []
    for entry in body.split("new[]")[1:]:
        strings = re.findall(r'"((?:[^"\\]|\\.)*)"', re.sub(r"/\*.*?\*/", "", entry, flags=re.S))
        name, units = strings[0], "".join(strings[1:])
        bounds = [int(h, 16) for h in re.findall(r"\\u([0-9A-Fa-f]{4})", units)]
        if len(bounds) * 6 != len(units):
            sys.exit(f"{name}: unexpected range text")
        # Pairs of first and one-past-last; an odd count leaves the last range open to U+FFFF.
        if len(bounds) % 2:
            bounds.append(0x10000)
        out.append((name, [(bounds[i], bounds[i + 1] - 1) for i in range(0, len(bounds), 2)]))
    if not out or out[0][0] != "IsAlphabeticPresentationForms" or out[-1][0] != "_xmlW":
        sys.exit("s_propTable not found as expected")
    return out


def rows(items, per_row):
    return "".join(
        "    " + " ".join(items[i : i + per_row]) + "\n" for i in range(0, len(items), per_row)
    )


def main():
    cat = categories(fetch(UNICODE_DATA))
    starts = [c for c in range(0x10000) if c == 0 or cat[c] != cat[c - 1]]
    table = blocks(fetch(REGEX_CHAR_CLASS))

    w = sys.stdout.write
    w("//! Generated by runner/tools/gen_unicode_tables.py; do not edit. What `\\p{…}` in regex.zig\n")
    w("//! reads: the general category of each UTF-16 code unit, from the Unicode Character\n")
    w("//! Database (UnicodeData.txt, Unicode 15.0.0, as .NET 8 has it), and .NET 8's named blocks\n")
    w("//! (RegexCharClass.s_propTable in dotnet/runtime v8.0.0).\n\n")
    w("/// .NET's UnicodeCategory, in its order.\n")
    w("pub const Category = enum(u5) { " + ", ".join(CATEGORIES) + " };\n\n")
    w("/// Run i covers code units `run_starts[i]` up to the next run's start, all of category\n")
    w("/// `run_categories[i]`.\n")
    w(f"pub const run_starts = [{len(starts)}]u16{{\n")
    w(rows([f"0x{c:04X}," for c in starts], 12))
    w("};\n\n")
    w(f"pub const run_categories = [{len(starts)}]Category{{\n")
    w(rows([f".{cat[c]}," for c in starts], 16))
    w("};\n\n")
    w("/// A block's ranges are `block_ranges[first..][0..count]`, first and last inclusive.\n")
    w("pub const Block = struct { name: []const u8, first: u16, count: u16 };\n\n")
    w(f"pub const blocks = [{len(table)}]Block{{\n")
    flat = []
    for name, ranges in table:
        w(f'    .{{ .name = "{name}", .first = {len(flat)}, .count = {len(ranges)} }},\n')
        flat.extend(ranges)
    w("};\n\n")
    w(f"pub const block_ranges = [{len(flat)}][2]u16{{\n")
    w(rows([f".{{ 0x{a:04X}, 0x{b:04X} }}," for a, b in flat], 5))
    w("};\n")


main()
